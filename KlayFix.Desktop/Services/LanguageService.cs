    private string _currentCulture = "en";

    public static LanguageService Instance { get; } = new();

    public string this[string key]
    {
        get
        {
            if (_strings.TryGetValue(_currentCulture, out var lang) && lang.TryGetValue(key, out var value))
                return value;
            if (_currentCulture != "en" && _strings.TryGetValue("en", out var enLang) && enLang.TryGetValue(key, out var enValue))
                return enValue;
            return key;
        }
    }

    public string CurrentCulture => _currentCulture;

    public bool IsRtl => _currentCulture == "ar";

    public System.Windows.FlowDirection FlowDirection => IsRtl ? System.Windows.FlowDirection.RightToLeft : System.Windows.FlowDirection.LeftToRight;

    public void SetLanguage(string cultureCode)
    {
        if (!_strings.ContainsKey(cultureCode)) return;
        _currentCulture = cultureCode;
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs("Item[]"));
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(CurrentCulture)));
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(IsRtl)));
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(FlowDirection)));
    }

    public ICommand SwitchToEnglishCommand { get; }
    public ICommand SwitchToArabicCommand { get; }

    public LanguageService()
    {
        SwitchToEnglishCommand = new RelayCommand(() => SetLanguage("en"));
        SwitchToArabicCommand = new RelayCommand(() => SetLanguage("ar"));
    }

    public event PropertyChangedEventHandler? PropertyChanged;
